// Writes app/generated/base-scoped.css: the base theme, scoped to
// [data-brand="base"], built from the installed package's base-light.css and
// base-dark.css. The site wears a demo brand on <html>, so the Themes page
// needs a way back to base for its "Base" panel. The package ships a scoped
// file for every brand but base (decisions/0001), so until it does, this
// derives one. Nothing is copied by hand: every value comes from the package.
//
// Same shape as the package's own *-scoped.css (sd.config.mjs): the dark
// block repeats every light declaration too, so a dark panel inside another
// brand never keeps one of that brand's values; and the dark block comes
// first, so a light panel inside a dark page ([data-mode="dark"]
// [data-brand="base"][data-mode="light"]) wins the tie on source order.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const BRANDS = join(ROOT, 'node_modules', '@amezquita', 'design-system', 'styles', 'brands')
const OUT_DIR = join(ROOT, 'app', 'generated')

function declarations(file, selector) {
  const css = readFileSync(join(BRANDS, file), 'utf8')
  const start = css.indexOf(`${selector} {`)
  if (start < 0 || css.indexOf('{', start + selector.length + 2) >= 0) {
    throw new Error(
      `build-base-scoped: expected ${file} to hold one block, "${selector} { … }". ` +
      'The package changed shape; update scripts/build-base-scoped.mjs.',
    )
  }
  const body = css.slice(css.indexOf('{', start) + 1, css.lastIndexOf('}'))
  const decls = new Map()
  for (const line of body.split(';')) {
    const i = line.indexOf(':')
    if (i < 0) continue
    decls.set(line.slice(0, i).trim(), line.slice(i + 1).trim())
  }
  return decls
}

const light = declarations('base-light.css', ':root, [data-mode="light"]')
const dark = new Map([...light, ...declarations('base-dark.css', '[data-mode="dark"]')])

const block = (selectors, decls) =>
  `${selectors.join(',\n')} {\n${[...decls].map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`

const css = [
  '/* Generated by scripts/build-base-scoped.mjs from the installed package. Do not edit. */\n',
  block(
    ['[data-brand="base"][data-mode="dark"]', '[data-brand="base"] [data-mode="dark"]', '[data-mode="dark"] [data-brand="base"]'],
    new Map([['color-scheme', 'dark'], ...dark]),
  ),
  block(
    ['[data-brand="base"]', '[data-brand="base"][data-mode="light"]', '[data-brand="base"] [data-mode="light"]'],
    new Map([['color-scheme', 'light'], ...light]),
  ),
].join('\n')

mkdirSync(OUT_DIR, { recursive: true })
writeFileSync(join(OUT_DIR, 'base-scoped.css'), css)
console.log(`build-base-scoped: ${light.size} light and ${dark.size} dark declarations`)
